// Turns the Markdown files in /content into seed.sql (lesson rows for D1).
// Usage: node scripts/build-seed.mjs   → writes seed.sql
// Uses INSERT OR IGNORE, so re-running never overwrites lessons you edited in the admin panel.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, basename, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'content');
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

function parseFile(text) {
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  const starts = [];
  lines.forEach((l, i) => { if (l.trim() === '---' && /^title:/.test(lines[i + 1] || '')) starts.push(i); });
  return starts.map((s, k) => {
    const end = k + 1 < starts.length ? starts[k + 1] : lines.length;
    const block = lines.slice(s + 1, end);
    const fmEnd = block.findIndex((l) => l.trim() === '---');
    const meta = {};
    for (const l of block.slice(0, fmEnd)) {
      const m = l.match(/^(\w+):\s*(.*)$/);
      if (m) meta[m[1]] = m[2].replace(/^"(.*)"$/, '$1').trim();
    }
    const body = block.slice(fmEnd + 1).join('\n');
    const [content, quiz = ''] = body.split(/^===QUIZ===\s*$/m);
    return { meta, content: content.trim() + '\n', quiz: quiz.trim() };
  });
}

let sql = '-- Generated by scripts/build-seed.mjs. Do not edit by hand; edit /content/*.md instead.\n';
let count = 0;
for (const file of readdirSync(dir).filter((f) => f.endsWith('.md')).sort()) {
  const track = basename(file, '.md');
  for (const { meta, content, quiz } of parseFile(readFileSync(join(dir, file), 'utf8'))) {
    if (!meta.slug || !meta.title) throw new Error(`Missing slug/title in ${file}`);
    sql += `INSERT OR IGNORE INTO lessons (track_id, slug, title, summary, sort, is_free, xp, kind, minutes, video_url, content_md, quiz_text, is_published, updated_at) VALUES (` +
      [
        `(SELECT id FROM tracks WHERE slug = ${q(track)})`, q(meta.slug), q(meta.title), q(meta.summary || ''),
        Number(meta.sort || 0), meta.free === 'true' ? 1 : 0, Number(meta.xp || 20), q(meta.kind || 'lesson'),
        Number(meta.minutes || 10), meta.video ? q(meta.video) : 'NULL', q(content), q(quiz), 1, Date.now(),
      ].join(', ') + ');\n';
    count++;
  }
}
writeFileSync(join(root, 'seed.sql'), sql);
console.log(`seed.sql written with ${count} lessons`);
